const char nl = '\n';

void solve() {
    int n, k;
    cin >> n >> k;
    
    map<int, int> C;
    int maxC = 0;
    F0R(i, n) {
        int a;
        cin >> a;
        if(C.count(a)) {
            C[a]++;
        } else {
            C[a] = 1;
        }
        maxC = max(maxC, C[a]);
    }

    int ans = 0;
    TRAV(e, C) {
        auto cnt = e.sc;
        if(maxC - cnt <= 1) {
            ans ++;
        }
    }
    cout << ans << nl;
}

int32_t main() {
    cin.tie(0)->sync_with_stdio(0);
    cin.exceptions(cin.failbit);

    int T = 1;
    #ifdef LOCAL
    #warning "LOCAL ONLY: reading T for multi-test"
    cin >> T;
    #endif

    while(T--) {
        solve();
        debug_print("TEST_CASE_DIV_LINE");
    }

    debug_print("EXECUTION_TIME");
    return 0;
}



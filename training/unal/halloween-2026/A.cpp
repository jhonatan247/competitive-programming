const char nl = '\n';

void solve() {
    string s;
    getline(cin, s);
    
    vector<char> vowels = { 'a', 'e', 'i', 'o', 'u', 'y'};

   
    int i = sz(s) - 1;;
    while(i and (s[i] == '?' or s[i] == ' ')) i--;
    
    TRAV(v, vowels) {
        if(tolower(s[i]) == v) {
            cout << "YES" << nl;
            return;
        }
    }

    cout << "NO" << nl;
    return;
}

